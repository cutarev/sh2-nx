#!/usr/bin/env python3
"""Resolve SH2 Enhancements addresses for the v1.0 exe (game/sh2pc.exe).

EE's SearchAndGetAddresses(v10, v11, dc, bytes, n, off) checks `bytes` at the v1.0 address (or
searches for them) and returns address + off; ReadSearchedAddresses reads the DWORD found there.
"""
import os, struct

EXE = os.path.join(os.path.dirname(__file__), '..', 'game', 'sh2pc.exe')
BASE = 0x400000
D = open(EXE, 'rb').read()


def search(hint, pat):
    o = hint - BASE
    if D[o:o + len(pat)] == pat:
        return hint
    i = D.find(pat)
    assert i >= 0 and D.find(pat, i + 1) < 0, f'pattern for {hint:#x} not unique/found'
    return i + BASE


def get(hint, pat, off):
    return search(hint, bytes(pat)) + off


def read(hint, pat, off):
    return struct.unpack_from('<I', D, get(hint, pat, off) - BASE)[0]


ADDR = {
    'room_id': read(0x0052A4A0, [0x83, 0xF8, 0x04, 0x0F, 0x87, 0xCE, 0x00, 0x00, 0x00], 0xD7 + 2),
    'event_index': read(0x0043F28A, [0x5E, 0xB8, 0x01, 0x00, 0x00, 0x00, 0x5B, 0xC3, 0x8B, 0xFF], -0x35),
    'menu_event': read(0x0044765D, [0x83, 0xC4, 0x04, 0x33, 0xF6, 0x56, 0x6A, 0x01, 0x68, 0xF0, 0x00, 0x00, 0x00,
                                     0x68, 0x00, 0x01, 0x00, 0x00, 0x6A, 0x1A, 0x50, 0xE8], -0x3E),
    'transition_state': read(0x0048E87B, [0x83, 0xF8, 0x19, 0x7E, 0x72, 0x83, 0xF8, 0x1A, 0x75, 0x05, 0xBF, 0x01, 0x00,
                                           0x00, 0x00, 0x39, 0x1D], 0x2A),
    'vibration_intensity': read(0x00461735, [0x6A, 0x60, 0x75, 0x04, 0x6A, 0x3F, 0xEB, 0x02, 0x6A, 0x1F, 0x6A, 0x3F,
                                              0x6A, 0x3F, 0xE8], -0x04),
    'rumble_flag': read(0x004589C1, [0x68, 0x10, 0x01, 0x00, 0x00, 0x50, 0xFF, 0x52, 0x24, 0x33, 0xD2, 0xB9], 0x0C) - 2,
    'menu_rumble_call': get(0x00497DD3, [0x53, 0x53, 0x53, 0x68, 0x10, 0x27, 0x00, 0x00, 0xC7, 0x05], -0x62),
    'set_vibration_params': get(0x458005, [0x83, 0xEC, 0x38, 0x83, 0xF8, 0x02, 0x75, 0x39], -0x5),
    'create_di_gamepad_jmp': get(0x458B30, [0x57, 0x33, 0xC0, 0xB9, 0x9F, 0x01, 0x00, 0x00], 0x24),
    'options_exit': get(0x004697AF, [0x08, 0x00, 0x00, 0x00, 0xEB, 0x0F, 0xB8, 0x10, 0x00, 0x00, 0x00, 0xA3], 0x06),
    'pause_game_call': get(0x00475839, [0x83, 0xC4, 0x0C, 0xB8, 0x01, 0x00, 0x00, 0x00, 0x5B, 0xC3, 0x90], -0x5F),
}
s = ADDR['set_vibration_params']
ADDR['gamepad_type'] = struct.unpack_from('<I', D, s + 1 - BASE)[0]
ADDR['di_effect_ptr'] = struct.unpack_from('<I', D, s + 0x34 + 1 - BASE)[0]

if __name__ == '__main__':
    for k, v in ADDR.items():
        print(f'#define EE_{k.upper():24} 0x{v:08X}u')
